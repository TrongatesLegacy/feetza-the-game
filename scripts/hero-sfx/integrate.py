"""Copy the hero SFX into the repo, credit them, and write their TRIM block in src/systems/audio.ts.
usage: integrate.py OUTDIR REPO"""
import json
import os
import re
import shutil
import sys

PACK = {
    'imp': ('Impact Sounds', 'https://kenney.nl/assets/impact-sounds'),
    'sci': ('Sci-fi Sounds', 'https://kenney.nl/assets/sci-fi-sounds'),
    'rpg': ('RPG Audio', 'https://kenney.nl/assets/rpg-audio'),
    'dgt': ('Digital Audio', 'https://kenney.nl/assets/digital-audio'),
    'ui': ('Interface Sounds', 'https://kenney.nl/assets/interface-sounds'),
    'uia': ('UI Audio', 'https://kenney.nl/assets/ui-audio'),
    'cas': ('Casino Audio', 'https://kenney.nl/assets/casino-audio'),
}
CC0 = 'https://creativecommons.org/publicdomain/zero/1.0/'


def what(key):
    k = key.replace('sfx_hero_', '')
    if key == 'music_tape':
        return 'Star-Lard’s Awesome Mix: the 12-second retro tape'
    if key == 'sfx_hero_end':
        return 'a hero transformation wears off'
    if k in ('flyby', 'glint', 'saucer', 'magic', 'squeak'):
        return f'a hero sighting streaks past ({k})'
    if k in ('catch', 'secret'):
        return 'a hero sighting is caught' if k == 'catch' else 'Batpeel’s Signal is found'
    if k in ('web', 'snip'):
        return 'Spider Socks webs a pizza' if k == 'web' else 'a Spider Sock’s thread is cut'
    return f'a hero peel move ({k})'


out, repo = sys.argv[1], sys.argv[2]
rep = [d for d in json.load(open(os.path.join(out, 'report.json'))) if 'error' not in d]
for d in rep:
    shutil.copy(os.path.join(out, d['key'] + '.mp3'), os.path.join(repo, 'public/audio', d['key'] + '.mp3'))


def kenney_list(used):
    by = {}
    for u in used:
        p, n = u.split('/')
        by.setdefault(p, []).append(n)
    return ' and '.join(f"{PACK[p][0]} {', '.join(ns)}" for p, ns in by.items())


def credit(d):
    k = d['key']
    w = f"Hero peels: {what(k)}"
    used, syn = d['used'], d['syn']
    if syn:
        notes = f'{w}; {syn}, made with ffmpeg and Python and released as CC0'
        if used:
            notes += f', layered with Kenney {kenney_list(used)} (CC0, kenney.nl)'
        return dict(file=k + '.mp3', title='Original synthesized sound', author='Made for Feetza', license='CC0 1.0', url=CC0, notes=notes)
    pk, name = used[0].split('/')
    notes = w
    if used[1:]:
        notes += f'; layered with {kenney_list(used[1:])} (Kenney, CC0)'
    return dict(file=k + '.mp3', title=f'{PACK[pk][0]} ({name})', author='Kenney (kenney.nl)', license='CC0 1.0', url=PACK[pk][1], notes=notes)


# credits.json and CREDITS.md: replace this set's rows (so a rebuild re-credits cleanly)
mine = {d['key'] + '.mp3' for d in rep}
cj = os.path.join(repo, 'public/audio/credits.json')
data = [e for e in json.load(open(cj)) if e['file'] not in mine]
new = [credit(d) for d in rep]
data += new
json.dump(data, open(cj, 'w'), indent=2, ensure_ascii=False)
open(cj, 'a').write('\n')

md = os.path.join(repo, 'public/audio/CREDITS.md')
lines = [ln for ln in open(md).read().split('\n') if not any(f'`{f}`' in ln for f in mine)]
text = '\n'.join(lines)
rows = ''.join(f"| `{c['file']}` | {c['title']} | {c['author']} | [CC0 1.0]({CC0}) | {c['url']} | {c['notes']} |\n" for c in new)
marker = '\nCC0 sounds need no attribution'
i = text.index(marker)
text = text[:i].rstrip('\n') + '\n' + rows + text[i:]
open(md, 'w').write(text)

# TRIM: one generated block, between markers
au = os.path.join(repo, 'src/systems/audio.ts')
src = open(au).read()
block = '  // ——— hero peels (generated by scripts/hero-sfx/integrate.py) ———\n' + ''.join(
    f"  {d['key']}: {d['trim']}, // {d['measured']} dB → {d['target']}\n" for d in rep) + '  // ——— end hero peels ———\n'
src = re.sub(r"  // ——— hero peels \(generated.*?// ——— end hero peels ———\n", '', src, flags=re.S)
anchor = '  // Stings are normalised to the music loudness'
src = src.replace(anchor, block + anchor, 1)
open(au, 'w').write(src)
print(len(new), 'credited and trimmed')
