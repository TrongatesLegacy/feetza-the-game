"""Copy the Persian army SFX into the repo, credit them (CREDITS.md and credits.json), and write their TRIM lines in
src/systems/audio.ts (after the god peels' feet). Every layer is synthesized in build.py, so each one is CC0.
usage: integrate.py OUTDIR REPO"""
import json
import os
import re
import shutil
import sys

CC0 = 'https://creativecommons.org/publicdomain/zero/1.0/'

WHAT = {
    'sfx_immortalreturn': 'Immortal Sandals: another Immortal steps into a fallen one’s place',
    'sfx_immortalfall': 'Immortal Sandals: a burning Immortal falls for good',
    'sfx_bowdraw': 'Archer Slippers draw their bow (the tell)',
    'sfx_arrowloose': 'Archer Slippers loose an arrow at the peel',
    'sfx_arrowthunk': 'an Archer Slippers arrow lands (and pins the peel)',
    'sfx_gallop': 'Cavalry Hooves gallop across',
    'sfx_neigh': 'Cavalry Hooves rear before a gallop, or trip when smacked mid-gallop',
    'sfx_chariotrev': 'Chariot Wheel revs before it rolls (the tell)',
    'sfx_chariotroll': 'Chariot Wheel rolls along the row of pizzas',
    'sfx_chariotchip': 'Chariot Wheel chips a slice off a pizza',
    'sfx_hubbreak': 'Chariot Wheel: its hub is smacked and the wheel breaks',
    'sfx_satrapbuff': 'Satrap’s Slipper armours a Persian foot',
    'sfx_warhorn': 'a Persian war band arrives',
}

out, repo = sys.argv[1], sys.argv[2]
rep = [d for d in json.load(open(os.path.join(out, 'report.json'))) if 'error' not in d]
# Files since re-made from real recordings by scripts/real-sfx/build.py (the audio pass, docs/audio-audit.md): not
# copied over, so running this again doesn't put the synthesized versions back (their credits and TRIM entries are
# only ever added when missing, so they are left as they are too).
REAL = {
    'sfx_immortalfall', 'sfx_bowdraw', 'sfx_arrowloose', 'sfx_arrowthunk', 'sfx_gallop', 'sfx_neigh',
    'sfx_chariotrev', 'sfx_chariotroll', 'sfx_chariotchip', 'sfx_hubbreak', 'sfx_warhorn',
}
for d in rep:
    if d['key'] not in REAL:
        shutil.copy(os.path.join(out, d['key'] + '.mp3'), os.path.join(repo, 'public/audio', d['key'] + '.mp3'))

md_path = os.path.join(repo, 'public/audio/CREDITS.md')
md = open(md_path).read()
js_path = os.path.join(repo, 'public/audio/credits.json')
js = json.load(open(js_path))
have = {e['file'] for e in js}
rows = []
for d in rep:
    f = d['key'] + '.mp3'
    notes = f"{WHAT[d['key']]}; {d['syn']}, made with ffmpeg and Python and released as CC0"
    if f not in have:
        js.append(dict(file=f, title='Original synthesized sound', author='Made for Feetza', license='CC0 1.0', url=CC0, notes=notes))
    if f'`{f}`' not in md:
        rows.append(f'| `{f}` | Original synthesized sound | Made for Feetza | [CC0 1.0]({CC0}) | {CC0} | {notes} |')
json.dump(js, open(js_path, 'w'), indent=2, ensure_ascii=False)
open(js_path, 'a').write('\n')
if rows:
    # straight after the Kratos Peel's feet, so they sit in the same table
    lines = md.split('\n')
    last = next(i for i, l in enumerate(lines) if l.startswith('| `sfx_bronzeshield.mp3`'))
    lines[last + 1:last + 1] = rows
    open(md_path, 'w').write('\n'.join(lines))

au_path = os.path.join(repo, 'src/systems/audio.ts')
au = open(au_path).read()
block = ['  // ——— the Persian army (generated by scripts/persian-sfx/integrate.py) ———']
for d in rep:
    if re.search(rf"^\s*{d['key']}:", au, re.M):
        continue
    block.append(f"  {d['key']}: {d['trim']:.2f}, // {d['measured']:.1f} dB → {d['target']:.1f}")
if len(block) > 1:
    anchor = re.search(r'^  sfx_bronzeshield: .*$', au, re.M)
    assert anchor
    au = au[:anchor.end()] + '\n' + '\n'.join(block) + au[anchor.end():]
    open(au_path, 'w').write(au)
print(len(rep), 'sounds integrated')
